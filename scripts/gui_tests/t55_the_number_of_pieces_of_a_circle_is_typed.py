"""Inside a circle the box of the diameter has a second field, Pieces: Tab goes to it, a typed number sets the pieces (up to 100), the right button still adds one and
Shift + the right button takes one away (the field follows), the left click draws them all as one step of Ctrl+Z."""
# FIXTURE: box 100 60 10
# POINTS: top=50,30,10;cc=50,30,10;cr=75,30,10;pc=62,30,10;pr=65,30,10
from guitest import *

time.sleep(1.0)
focus_app_window()
p = settle()
click(*screen(p, "top"))
key("k")
p = settle(0.5)
key("c")
settle(0.3)
click(*screen(p, "cc"))
click(*screen(p, "cr"))
p = settle(0.4)
n0 = lambda q: len(q["circles"])
check(n0(p) == 1, f"the big circle: {n0(p)}")
click(*screen(p, "pc"))
p = settle(0.4)
move(*screen(p, "pr"))
time.sleep(0.6)
p = probe()
check(p["extra"]["pieces"]["available"], f"the field of the pieces is there inside a circle: {p['extra']['pieces']}")
key("Tab")
type_text("12")
p = settle(0.4)
pc = p["extra"]["pieces"]
check(pc["editing"] and pc["n"] == 12 and p["multi_copies"] == 11, f"12 typed: {pc}, copies {p['multi_copies']}")
shot("01-twelve")
key("BackSpace")
key("BackSpace")
type_text("7")
p = settle(0.4)
check(p["extra"]["pieces"]["n"] == 7, f"7 typed: {p['extra']['pieces']}")
right_click()
p = settle(0.4)
check(p["extra"]["pieces"]["n"] == 8, f"the right button adds one: {p['extra']['pieces']}")
right_click(shift=True)
p = settle(0.4)
check(p["extra"]["pieces"]["n"] == 7, f"Shift + the right button takes one away: {p['extra']['pieces']}")
# the most is 100
key("Tab")
key("Tab")
for _ in range(3):
    key("BackSpace")
type_text("250")
p = settle(0.4)
check(p["extra"]["pieces"]["n"] == 100, f"a hundred at the most: {p['extra']['pieces']}")
shot("02-hundred")
key("BackSpace")
key("BackSpace")
key("BackSpace")
type_text("9")
p = settle(0.4)
check(p["extra"]["pieces"]["n"] == 9, f"9: {p['extra']['pieces']}")
click(*screen(p, "pr"))
p = settle(0.8)
check(n0(p) == 10, f"the big circle and nine small ones: {n0(p)}")
check(len(p["extra"]["regions_selected"]) == 9, f"the nine new circles are all selected (P pulls them at once): {p['extra']['regions_selected']}")
key("p")
p = settle(0.5)
check(p["tool"] == "Pull" and len(p["extra"]["regions_selected"]) == 9, f"after the switch to P they are still selected: {p['tool']} {len(p['extra']['regions_selected'])}")
key("z", ctrl=True)
settle(0.3)
shot("03-drawn")
p = settle(0.5)
check(n0(p) == 1, f"one Ctrl+Z takes back all nine: {n0(p)}")
finish()
