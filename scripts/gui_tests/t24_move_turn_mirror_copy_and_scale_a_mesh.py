"""A whole mesh: the panel of the Move tool (X, Y, Z, an angle, Copy), a pattern (T), a mirror (B) and the scale in the panel of the selection, uniform and in one direction;
every step is one step of Undo; a rounding is refused with a sentence."""
# FIXTURE: import-stl examples/stl/plate-with-hole.stl; mesh-to-doc
# POINTS: top=10,10,10
from guitest import *

time.sleep(1.0)
focus_app_window()
p = wait_for(lambda q: q["meshes"] and q["meshes"][0]["walls"] is not None, "the walls are found", 30)
# move by 100 mm along X
key("m")
settle(0.4)
click(*screen(p, "top"))
p = settle(0.8)
click(*screen(p, "move_field_0"))
type_text("100")
click(*screen(p, "move_apply"))
p = wait_for(lambda q: q["meshes"][0]["bbox"][0] > 99, "the mesh moved", 20)
check(close(p["meshes"][0]["bbox"][0], 100.0, 0.001) and close(p["meshes"][0]["bbox"][3], 160.0, 0.001), f"moved by 100 mm in X: {p['meshes'][0]['bbox']}")
key("z", ctrl=True)
p = wait_for(lambda q: q["meshes"][0]["bbox"][0] < 1, "Undo", 20)
# turn by 90 degrees about Z: 60 x 40 becomes 40 x 60 (Undo leaves the tool: the mesh is clicked again)
p = settle(0.5)
click(*screen(p, "top"))
p = settle(0.8)
click(*screen(p, "move_field_0"))
key("a", ctrl=True)
type_text("0")
click(*screen(p, "move_field_3"))
type_text("90")
click(*screen(p, "move_axis_2"))
click(*screen(p, "move_apply"))
p = wait_for(lambda q: abs(q["meshes"][0]["bbox"][3] - q["meshes"][0]["bbox"][0] - 40) < 0.01, "the mesh turned", 20)
shot("01-turned")
key("z", ctrl=True)
p = wait_for(lambda q: abs(q["meshes"][0]["bbox"][3] - q["meshes"][0]["bbox"][0] - 60) < 0.01, "Undo of the turn", 20)
# a copy 70 mm away
p = settle(0.5)
click(*screen(p, "top"))
p = settle(0.8)
click(*screen(p, "move_field_3"))
key("a", ctrl=True)
type_text("0")
click(*screen(p, "move_field_0"))
key("a", ctrl=True)
type_text("70")
click(*screen(p, "move_copy"))
click(*screen(p, "move_apply"))
p = wait_for(lambda q: len(q["meshes"]) == 2, "a copy was made", 20)
check(close(p["meshes"][1]["bbox"][0], 70.0, 0.001), f"the copy lies 70 mm away: {p['meshes'][1]['bbox']}")
shot("02-copy")
key("z", ctrl=True)
p = wait_for(lambda q: len(q["meshes"]) == 1, "Undo of the copy", 20)
# the pattern tool: three pieces (the mesh is marked with the Move tool first)
p = settle(0.5)
click(*screen(p, "top"))
p = settle(0.8)
key("t")
p = settle(0.6)
click(*screen(p, "link_apply"))
p = wait_for(lambda q: len(q["meshes"]) == 3, "a pattern of three", 20)
check(close(p["meshes"][2]["bbox"][0] - p["meshes"][1]["bbox"][0], p["meshes"][1]["bbox"][0] - p["meshes"][0]["bbox"][0], 0.01), "equal steps")
shot("03-pattern")
key("z", ctrl=True)
p = wait_for(lambda q: len(q["meshes"]) == 1, "Undo of the pattern", 20)
# mirror
key("m")
p = settle(0.5)
click(*screen(p, "top"))
p = settle(0.8)
key("b")
p = settle(0.6)
click(*screen(p, "link_apply"))
p = wait_for(lambda q: len(q["meshes"]) == 2, "a mirror image", 20)
check(close(p["meshes"][1]["bbox"][3], 0.0, 0.01), f"the image lies on the other side of the plane: {p['meshes'][1]['bbox']}")
check(close(p["meshes"][1]["volume"], p["meshes"][0]["volume"], 0.01), "the mirror image is not inside out (the same volume)")
shot("04-mirror")
key("z", ctrl=True)
p = wait_for(lambda q: len(q["meshes"]) == 1, "Undo of the mirror", 20)
# scale in the panel of the selection: select the mesh in the list, 2 in x, 1, 0.5 in z
key("s")
p = settle(0.4)
click(*screen(p, "mesh_row_1"))
p = settle(0.6)
click(*screen(p, "mesh_scale_x"))
key("a", ctrl=True)
type_text("2")
click(*screen(p, "mesh_scale_z"))
key("a", ctrl=True)
type_text("0.5")
click(*screen(p, "mesh_scale_apply"))
p = wait_for(lambda q: abs(q["meshes"][0]["bbox"][3] - q["meshes"][0]["bbox"][0] - 120) < 0.01, "scaled", 20)
b = p["meshes"][0]["bbox"]
check(close(b[4] - b[1], 40.0, 0.01) and close(b[5] - b[2], 5.0, 0.01), f"120 x 40 x 5 mm: {b}")
shot("05-scaled")
key("z", ctrl=True)
p = wait_for(lambda q: abs(q["meshes"][0]["bbox"][3] - q["meshes"][0]["bbox"][0] - 60) < 0.01, "Undo of the scale", 20)
# a round of an edge is refused with a sentence
key("f")
p = settle(0.5)
check(len(p["meshes"]) == 1, "still one mesh")
finish()
